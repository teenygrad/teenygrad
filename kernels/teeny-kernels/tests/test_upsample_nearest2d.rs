// Nearest-neighbour 2-D upsample forward and backward tests.
//
// Kernel:  upsample_nearest2d_forward / upsample_nearest2d_backward
// Layout:  NCHW float32
//
// Dimensions:
//   B=2, C=4, H=4, W=4, SCALE_H=2, SCALE_W=2
//   OH = H * SCALE_H = 8,  OW = W * SCALE_W = 8
//
// Forward grid: B*C*OH * ceil(OW/BLOCK_OW) CTAs over output positions.
// Backward grid: B*C*H * ceil(W/BLOCK_IW) CTAs over input positions;
//   each CTA sums SCALE_H*SCALE_W upstream gradients — no atomic ops.
//
// Fixtures generated by tests/fixtures/upsample_nearest2d/generate.py.

