#[cfg(feature = "hardware")]
const C: usize = 4;
#[cfg(feature = "hardware")]
const H: usize = 4;
#[cfg(feature = "hardware")]
const W: usize = 4;
const SCALE_H: i32 = 2;
const SCALE_W: i32 = 2;
#[cfg(feature = "hardware")]
const OH: usize = H * SCALE_H as usize; // 8
#[cfg(feature = "hardware")]
const OW: usize = W * SCALE_W as usize; // 8
const BLOCK_OW: i32 = 4;

